const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  
  // 1. Deploy Mock Chainlink Feed (Local Testing)
  const MockV3Aggregator = await hre.ethers.getContractFactory("MockV3Aggregator");
  const mockFeed = await MockV3Aggregator.deploy(8, 2000 * 10**8); // $2000 ETH
  await mockFeed.waitForDeployment();
  const mockFeedAddress = await mockFeed.getAddress();
  console.log("Mock ETH/USD Feed deployed to:", mockFeedAddress);

  // 2. Deploy Main Contract
  const Factory = await hre.ethers.getContractFactory("SupplierCompliance");
  const contract = await Factory.deploy(mockFeedAddress);
  await contract.waitForDeployment();

  const address = await contract.getAddress();
  console.log("SupplierCompliance deployed to:", address);

  // 3. Update Frontend ABI & Address
  const frontendDir = path.join(__dirname, "..", "frontend");
  if (!fs.existsSync(frontendDir)) fs.mkdirSync(frontendDir, { recursive: true });

  const artifact = await hre.artifacts.readArtifact("SupplierCompliance");
  const content = `// AUTO-GENERATED by scripts/deploy.js
window.CONTRACT_ADDRESS = "${address}";
window.CONTRACT_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;
  fs.writeFileSync(path.join(frontendDir, "contract-info.js"), content);
  console.log("✅ Frontend contract-info.js written.");
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});